export function getTemplateBySlug(slug: string): SowTemplate | undefined {
  return SOW_TEMPLATES.find((t) => t.slug === slug);
}

export function buildDocumentFromTemplate(
  template: SowTemplate,
  existingBrand?: SowDocument["brand"]
): SowDocument {
  const today = new Date();
  const plusDays = (days: number) => {
    const d = new Date(today);
    d.setDate(d.getDate() + days);
    return d.toISOString().slice(0, 10);
  };

  const preset = template.presetDocument;

  return {
    id: `doc-${Date.now()}`,
    mode: preset.mode,
    templateSlug: template.slug,
    documentNumber: preset.documentNumber,
    parentSowNumber: preset.parentSowNumber,
    projectTitle: preset.projectTitle,
    summary: preset.summary,
    issueDate: plusDays(0),
    validUntil: plusDays(14),
    targetStartDate: plusDays(5),
    targetEndDate: plusDays(35),
    currency: preset.currency,
    taxRate: preset.taxRate,
    providerName: "Northstar Digital Studio LLC",
    providerContact: "Alex Mercer, Principal",
    providerEmail: "hello@northstardigital.co",
    providerLocation: "Austin, TX",
    clientCompany: "Acme Commerce Inc.",
    clientContact: "Jordan Vance, VP Operations",
    clientEmail: "jordan@acmecommerce.com",
    deliverables: preset.deliverables.map((d) => ({ ...d })),
    exclusions: [...preset.exclusions],
    milestones: preset.milestones.map((m) => ({ ...m })),
    revisionRounds: preset.revisionRounds,
    changeOrderRate: preset.changeOrderRate,
    acceptanceBusinessDays: preset.acceptanceBusinessDays,
    killFeePercent: preset.killFeePercent,
    ipTransferOnFullPayment: preset.ipTransferOnFullPayment,
    lateFeeMonthlyPercent: preset.lateFeeMonthlyPercent,
    governingState: preset.governingState,
    includePricingOptions: preset.includePricingOptions,
    pricingOptions: preset.pricingOptions.map((o) => ({ ...o })),
    timelineImpactDays: preset.timelineImpactDays,
    changeReason: preset.changeReason,
    brand: existingBrand ?? {
      accentColor: "#0F5C4A",
      logoDataUrl: "",
      customFooter: "",
    },
  };
}
