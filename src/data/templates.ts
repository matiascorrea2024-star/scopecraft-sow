function stdMilestones(a = 50, b = 30, c = 20) {
  return [
    { id: "m1", label: "Kickoff Deposit", percentage: a, dueTrigger: "Upon signing (before work begins)" },
    { id: "m2", label: "Staging / Midpoint Review", percentage: b, dueTrigger: "Upon staging or draft delivery" },
    { id: "m3", label: "Final Sign-Off & Handoff", percentage: c, dueTrigger: "Prior to production launch / source transfer" },
  ];
}

function retainerMilestones() {
  return [
    { id: "m1", label: "Month 1 Retainer (Upfront)", percentage: 50, dueTrigger: "Net 0 upon signing" },
    { id: "m2", label: "Mid-Cycle Deliverable Check", percentage: 25, dueTrigger: "Day 15 of active billing cycle" },
    { id: "m3", label: "End-of-Cycle Report & Renewal", percentage: 25, dueTrigger: "Day 30 upon monthly report delivery" },
  ];
}

